  /* 上一次每类挑中的下标：避免连着两次说同一句 */
  var last = {};

  function fill(t, vars) {
    if (!vars) return t;
    return String(t).replace(/\{(\w+)\}/g, function (m, k) {
      return (vars[k] != null && vars[k] !== '') ? String(vars[k]) : m;
    });
  }

  function has(cat) {
    return !!(T[cat] && T[cat].length);
  }

  /* ---------- 多音字：送 TTS 前换成同音字，屏幕上仍显示原名 ----------
     「还丹」的「还」多数中文音色会念成 hái（还有的还），
     小说 / 武侠里该念 huán（还原的还）。换成同音的「环」就必念 huán，
     听感完全一样，孩子听到的音没错，看到的字也没变。 */
  var PRON = {
    '小还丹': '小环丹',
    '大还丹': '大环丹'
  };

  function pron(text) {
    var s = String(text == null ? '' : text);
    if (!s) return s;
    for (var k in PRON) {
      if (Object.prototype.hasOwnProperty.call(PRON, k) && s.indexOf(k) >= 0) {
        s = s.split(k).join(PRON[k]);
      }
    }
    return s;
  }

  /** 随机挑一条并填好变量；同一类不会连着重复 */
  function pick(cat, vars) {
    var arr = T[cat];
    if (!arr || !arr.length) return '';
    var i = Math.floor(Math.random() * arr.length);
    if (arr.length > 1 && i === last[cat]) i = (i + 1) % arr.length;
    last[cat] = i;
    return fill(arr[i], vars);
  }

  /** 测试用：清掉「上次说了哪条」的记忆 */
  function reset() { last = {}; }

  global.ARCADE_LINES = { text: T, pick: pick, has: has, fill: fill, reset: reset, pron: pron, PRON: PRON };
