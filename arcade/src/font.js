  function draw(ctx, text, x, y, scale, color, outline) {
    scale = scale || 1;
    var s = String(text);
    var cx = Math.round(x);
    var cy = Math.round(y);
    if (outline) {
      var off = [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]];
      for (var o = 0; o < off.length; o++) {
        draw(ctx, s, cx + off[o][0] * scale, cy + off[o][1] * scale, scale, outline, null);
      }
    }
    ctx.fillStyle = color;
    for (var i = 0; i < s.length; i++) {
      var g = G[s[i]] || G[s[i].toUpperCase()];
      if (!g) { cx += 6 * scale; continue; }
      for (var r = 0; r < g.length; r++) {
        var row = g[r];
        for (var c = 0; c < 5; c++) {
          if (row[c] === '#') ctx.fillRect(cx + c * scale, cy + r * scale, scale, scale);
        }
      }
      cx += 6 * scale;
    }
    return cx;
  }

  function width(text, scale) {
    scale = scale || 1;
    return Math.max(0, String(text).length * 6 * scale - scale);
  }

  global.PixelFont = { draw: draw, width: width, glyphs: G };
